import { UserRole } from '../../common/enums/user-role.enum.js';

export enum TimelineEventType {
  PATIENT_CREATED = 'PATIENT_CREATED',
  PATIENT_UPDATED = 'PATIENT_UPDATED',
  APPOINTMENT_BOOKED = 'APPOINTMENT_BOOKED',
  APPOINTMENT_CONFIRMED = 'APPOINTMENT_CONFIRMED',
  APPOINTMENT_RESCHEDULED = 'APPOINTMENT_RESCHEDULED',
  APPOINTMENT_CANCELLED = 'APPOINTMENT_CANCELLED',
  APPOINTMENT_NO_SHOW = 'APPOINTMENT_NO_SHOW',
  NO_SHOW_UNDONE = 'NO_SHOW_UNDONE',
  VISIT_ATTENDED = 'VISIT_ATTENDED',
  ATTEND_UNDONE = 'ATTEND_UNDONE',
  INVOICE_ISSUED = 'INVOICE_ISSUED',
  INVOICE_CANCELLED = 'INVOICE_CANCELLED',
  DISCOUNT_APPLIED = 'DISCOUNT_APPLIED',
  DISCOUNT_REMOVED = 'DISCOUNT_REMOVED',
  PAYMENT_RECORDED = 'PAYMENT_RECORDED',
  PAYMENT_VOIDED = 'PAYMENT_VOIDED',
  PAYMENT_REFUNDED = 'PAYMENT_REFUNDED',
  NOTE_SIGNED = 'NOTE_SIGNED',
  ADDENDUM_ADDED = 'ADDENDUM_ADDED',
  MEDICAL_INFO_UPDATED = 'MEDICAL_INFO_UPDATED',
  ATTACHMENT_UPLOADED = 'ATTACHMENT_UPLOADED',
  PACKAGE_SOLD = 'PACKAGE_SOLD',
  PACKAGE_SESSION_USED = 'PACKAGE_SESSION_USED',
  PACKAGE_SESSION_RESTORED = 'PACKAGE_SESSION_RESTORED',
  PACKAGE_CANCELLED = 'PACKAGE_CANCELLED',
}

const T = TimelineEventType;

export const CLINICAL_EVENTS: readonly TimelineEventType[] = [
  T.NOTE_SIGNED,
  T.ADDENDUM_ADDED,
  T.MEDICAL_INFO_UPDATED,
  T.ATTACHMENT_UPLOADED,
];

export const BILLING_EVENTS: readonly TimelineEventType[] = [
  T.INVOICE_ISSUED,
  T.INVOICE_CANCELLED,
  T.DISCOUNT_APPLIED,
  T.DISCOUNT_REMOVED,
  T.PAYMENT_RECORDED,
  T.PAYMENT_VOIDED,
  T.PAYMENT_REFUNDED,
  // Carries the prices; the other package events have none.
  T.PACKAGE_SOLD,
];

// RECEPTIONIST: no clinical data. DOCTOR: no billing. OWNER: everything.
export function visibleEventTypes(role: UserRole): TimelineEventType[] {
  const hidden =
    role === UserRole.RECEPTIONIST
      ? CLINICAL_EVENTS
      : role === UserRole.DOCTOR
        ? BILLING_EVENTS
        : [];
  return Object.values(TimelineEventType).filter((t) => !hidden.includes(t));
}
